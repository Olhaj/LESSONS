// Объект event => это событие, которое происходит в браузере, создается
// автоматически при возникновении события и содержит
// информацию о событии, такую как тип события и целевой
// элемент.

// ------------- Основные методы объекта event---------
// .preventDefault() => Позволяет отменить стандартное поведение
// браузера по умолчанию при возникновении события.

// .stopPropagation() => Позволяет остановить распространение
// события дальше по цепочке элементов.

// .stopImmediatePropagation() => Позволяет остановить распространение
// события сразу же и предотвратить вызов других обработчиков
// этого же события.

// ---------- Обработчики событий в JavaScript --------
// inline обработчики событий => Определяются непосредственно
// в HTML элементе и вызываются при возникновении события

// .addEventListener() => Позволяет добавлять обработчики
// событий к элементам динамически и управлять порядком
// их выполнения.

// ------------- Свойства объекта event ----------------
// .target => Содержит ссылку на элемент DOM,
// на котором произошло событие.

// .type => Содержит тип события, например, 'click' или
// 'keydown'.

// .currentTarget => Содержит ссылку на элемент, на котором
// установлен обработчик текущего события.

