//! Статические свойства — это свойства
// это свойства, которые позволяют присваивать свойства
// непосредственно классу, а не его экземплярам.
// Доступны через имя класса, без необходимости создания
// экземпляра класса.

//* Использование статистических методов
// ● Полезны, когда требуется функциональность, которая
// не зависит от конкретного экземпляра класса, но все
// же связана с самим классом.
// ● Могут использоваться для выполнения общих операций,
// обработки данных или предоставления вспомогательных
// функций.
// ● Не имеют доступа к свойствам или методам экземпляров
// класса, так как они принадлежат самому классу, а не
// его экземплярам.

//? Пример:
// const arr1 = new Array(1, 2, 3);

// arr1.map(); //методы екземпляра
// =====================================================

//! Array.from() — это стандартный статический метод,
// который создает новый экземпляр Array из массивоподобного
// или итерируемого объекта.

//? Метод Array.from()
// console.log(Array.from("foo")); // ["f", "0", "0"]
//======================================================

//! Array.isArray() — это стандартный статический метод,
// который возвращает true, если объект является массивом
// и false, если он массивом не является.

//? Метод Array.isArray()
// console.log(Array.isArray("Array")); // false
// console.log(Array.isArray([1, 2, 3])); // true
//======================================================

//! Number.isInteger() — это стандартный статический метод,
// который определяет, является ли переданное значение
// целым числом.

//? Метод Number.isInteger()
// console.log(Number.isInteger(1)); // true
// console.log(Number.isInteger(2.5)); // false
//=======================================================

//! Object.keys() — это стандартный статический метод,
// который возвращает массив, содержащий имена всех собственных
// перечислимых свойств переданного объекта.

//? Метод Object.keys()
// const an_obj = { a: "1", b: "2", c: "3" };
// console.log(Object.keys(an_obj)); // ["a", "b", "c"]
//======================================================

