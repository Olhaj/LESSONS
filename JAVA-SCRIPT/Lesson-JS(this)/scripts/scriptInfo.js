//! call, apply и bind — это методы,
// которые позволяют указать контекст выполнения для функции.

//! call — это метод,
// который вызывает функцию с указанным значением
// this и индивидуально предоставленными аргументами.

//* Пример использования метода call()
function greet() {
  console.log(`Hello, ${this.name}`);
}
const user = { name: "Alex" };
greet.call(user);
// Hello, Alex

function greet(age) {
  console.log(`Name: ${this.name}, age: ${age}`);
}
const user1 = { name: "Alex" };
greet.call(user, 19);
// Name: Alex, age: 19
// ==============================================

//! apply — это метод,
// который вызывает функцию с указанным значением
// this и аргументами, предоставленными в виде массива.

//* Пример использования метода apply()
function sayHello(greeting, age) {
  console.log(`${greeting}, меня зовут ${this.name}, мне 25`);
}
const person = { name: "John" };
sayHello.apply(person, ["Привет", 25]);
// Привет, меня зовут John, мне 25
// ================================================

//! bind — это метод,
// который создает новую функцию, привязывая указанное
// значение this к функции. Возвращаемая функция может быть вызвана позже.

//* Пример использования метода bind()
function sayHello() {
  console.log(`Привет, меня зовут ${this.name}`);
}
const person1 = { name: "John" };
const boundFunction = sayHello.bind(person);
boundFunction(); // Выводит "Привет, меня зовут John"
