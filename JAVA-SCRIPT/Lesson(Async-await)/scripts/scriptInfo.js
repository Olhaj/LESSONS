//! Асинхронные функции — это функции,
// которые объявлены с использованием ключевого слова async.
// ?Особенности асинхронных функций
// ● В качестве результата асинхронная функция всегда возвращает промис.
// ● Асинхронные функции нужны для выполнения асинхронных операций:
//         ○ работой с API
//         ○ базами данных
//         ○ чтения файлов и т.д.
// ● Асинхронные операции выполняются не сразу: код отправил запрос к API и ждёт, пока сервер пришлет ответ.
// ● Ключевое слово await используется, чтобы дождаться выполнения асинхронной операции.

//* Примеры объявления стрелочной и именованной асинхронных функций
async function fetchSomething() {
  // асинхронный код
}
const fetchSomething = async () => {
  // асинхронный код
};
// ================================================================

//! await — это ключевое слово,
// которое используется для ожидания окончания Promise. Может быть
// использован только внутри асинхронной функции.

//* Пример использования await:
async function resolveAfter2Seconds(x) {
  return new Promise((resolve) => {
    setTimeout(() => {
      resolve(x);
    }, 2000);
  });
}

async function f1() {
  const x = await resolveAfter2Seconds(10);
  console.log(x); //10
}

f1();
