// !Async/await — это специальный синтаксис,
//  который предназначен для более простого и удобного написания асинхронного кода.

// *Использование async/await
// ● Синтаксис «async/await» упрощает работу с промисами (позволяет асинхронный код записывать синхронным способом).
// ● Ключевые слова async и await используются вместе для создания асинхронных функций и ожидания выполнения промисов.

// !Async — это ключевое слово перед функцией,
// которое указывает, что эта функция будет асинхронной и будет возвращать промис. Внутри асинхронной
// функции можно использовать ключевое слово await для ожидания выполнения промисов.

// !Await — это ключевое слово,
// которое используется внутри асинхронной функции для ожидания выполнения
// промиса. При использовании перед промисом, выполнение функции приостанавливается до тех
// пор, пока промис не будет разрешен или отклонен. Затем значение, разрешенное промисом,
// возвращается из await выражения.

// *Пример использования async/await
function fetchData() {
  return new Promise((resolve, reject) => {
    setTimeout(() => {
      resolve("Данные получены");
    }, 2000);
  });
}

async function getData() {
  const result = await fetchData();
  console.log(result);
}

getData();
