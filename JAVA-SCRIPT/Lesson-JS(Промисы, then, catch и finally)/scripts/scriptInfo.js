// !Promise — это объект,
// который содержит будущее значение
// асинхронной операции. Например, если вы
// запрашиваете некоторые данные с сервера, промис
// обещает нам получить эти данные, которые мы
// сможем использовать в будущем.

// *Использование промиса
// ● Решает задачу выполнения кода, который зависит
// от результата асинхронной операции.
// ● Рычаги управления его состоянием остаются у
// асинхронной функции.
// ● После создания, промис находится в состоянии
// ожидания pending.
// ● Когда асинхронная операция завершается, функция
// переводит промис в состояние успеха
// ?fulfilled
// или ошибки
// ?rejected.
// ● После того, как промис завершился, мы можем
// использовать его результат в методах
// ?then() и catch().

// *Пример:
// ● Веб-сайт загружает данные из базы данных
// ● Обрабатывает и форматирует полученные данные
// ● Отображает пользователю

// *Создание промисов
// const promise = new Promise((resolve, reject) => {
//   асинхронная операция
// ● Интерфейс Promise принимает аргумент executor
// - объект функции с двумя аргументами resolve и
// reject.
// ● Функция executor получает оба аргумента и
// выполняется сразу, еще до того как конструктор
// вернёт созданный объект.
// ● Первый аргумент (resolve) вызывает успешное
// исполнение промиса, второй (reject) отклоняет его.
// ● Функция executor описывает выполнение какой-то
// асинхронной работы, по завершении которой необходимо
// вызвать функцию resolve или reject.
// ● Возвращаемое значение функции executor
// игнорируется.

// *Пример создания простого промиса:
// const resolve = () => console.log("Промис выполнен успешно");
// const reject = () => console.log("Промис выполнен с ошибкой");

