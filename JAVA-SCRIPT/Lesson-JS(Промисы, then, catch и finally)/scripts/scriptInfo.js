// ● Если ни один из промисов не завершится успешно
// (если все промисы завершатся с ошибкой, т.е. rejected),
// тогда возвращенный объект Promise будет отклонен
// (rejected) с одним из значений:
//       ○ Массив содержащий причины ошибки (отклонения)
//       ○ AggregateError (en-US) — подкласс Error, который
// объединяет выброшенные ошибки вместе
// =========================================================

