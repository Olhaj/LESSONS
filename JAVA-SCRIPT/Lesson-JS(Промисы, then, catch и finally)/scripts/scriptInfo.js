// ?========= then, catch, finally ================
// Методы, позволяющие работать с результатом
// выполнения вычисления внутри промиса

// !then() — это метод,
// который используют, чтобы выполнить код
// после успешного выполнения асинхронной операции.
// Принимает в качестве аргумента две функции-колбэка.
// Если промис в состоянии fulfilled то выполнится первая
// функция. Если в состоянии rejected — вторая.

// *Пример метода then()
// const promise = new Promise((resolve, reject) => {
//     resolve("Промис выполнен успешно");
// });
// promise.then((result) => {
//     console.log(result); // "Промис выполнен успешно"
// });
// =================================================

// !catch() — это метод,
// который используют, чтобы выполнить код в
// случае ошибки при выполнении асинхронной операции.
// Принимает в качестве аргумента функцию-колбэк,
// которая выполняется сразу после того, как промис
// поменял состояние на
// ?rejected.

// *Пример метода catch()
// const promise = new Promise((resolve, reject) => {
//     reject("Промис выполнен с ошибкой");
// });

// promise
//     .then((result) => {
//     console.log(result);
// })
//     .catch((error) => {
//         console.log(error); // "Промис выполнен с ошибкой"
//     })
// =================================================

// !finally() — это метод,
// который используют, чтобы выполнить код
// при завершении асинхронной операции. Будет выполнен
// не зависимо от того, была ли операция успешной или
// завершилась ошибкой. Принимает в качестве аргумента
// функцию-колбэк, которая выполняется сразу после того,
// как промис поменял состояние на rejected или fulfilled.

// *Пример метода finally()
// const promise = new Promise((resolve, reject) => {
//     resolve("Промис выполнен успешно");
// });

// promise
//     .then((result) => {
//     console.log(result);
// })
//     .catch((error) => {
//         console.log(error);
//     })
//     .finally(() => {
//         console.log("Промис выполнен");
//     });
// =================================================

// !Promise.resolve(value) - это метод,
// который возвращает промис, который был успешно разрешен с \
// указанным значением. Если передается уже существующий промис,
// Promise.resolve возвращает его без изменений. Если передается
// объект (объект с методом then), Promise.resolve разрешает его
// в промис.

// *Пример использования Promise.resolve(value):
// const resolvedPromise = Promise.resolve("Значение успешно разрешено");
// resolvedPromise.then((result) => console.log(result));
// Выводит: "Значение успешно разрешено"
// ========================================================

// !Promise.reject(reason) — это метод,
// который возвращает промис, который был отклонен с указанной
// причиной (ошибкой). Обычно используется, когда возникает
// ошибка или невозможно выполнить обещание.

// *Пример использования Promise.reject(reason):
// const rejectdPromise = Promise.reject("Произошла ошибка");
// rejectdPromise.catch((error) => console.error(error));
// Выводит: "Произошла ошибка"
// =========================================================
// ?Использование Promise.resolve() и Promise.reject()
// ● Используются для создания исходных промисов
// ● Используются для обработки случаев успешного разрешения и отклонения в асинхронных операциях
// ● Полезны при обработке результатов асинхронных функций или при создании цепочек промисов
// =========================================================

// !Promise.all() — это метод,
// который возвращает массив значений от всех промисов,
// которые были ему переданы. Возвращаемый массив значений
// сохраняет порядок оригинального перечисляемого объекта,
// но не порядок выполнения промисов.

// *Пример использования Promise.all():
// const p1 = new Promise((resolve, reject) => {
//   setTimeout(resolve, 100, "John");
// });
// const p2 = "Jane";
// const p3 = Promise.resolve(3);

// Promise.all([p1, p2, p3]).then((values) => {
