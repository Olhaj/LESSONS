// !Promise.all(iterable) — это метод,
// который возвращает промис, который выполнится тогда,
// когда будут выполнены все промисы, переданные в виде
// перечисляемого аргумента, или отклонено любое из переданных
// промисов.
//==========================================================

// ?Работа метода Promise.all()
// ● Если какой-либо элемент перечисляемого объекта не
// является промисом, то он будет преобразован с помощью
// метода Promise.resolve.
// ● Если одно из переданных промисов будет отклонено,
// Promise.all будет немедленно отклонен со значением отклоненного
// промиса, не учитывая другие промисы, независимо выполнены
// они или нет.
// ● Если в качестве аргумента будет передан пустой массив,
// то Promise.all будет выполнен немедленно.
//==========================================================

// !Promise.allSettled() — это метод,
// который возвращает промис, который исполняется когда все
// полученные промисы завершены (исполнены или отклонены),
// содержащий массив результатов исполнения полученных промисов.

// *Пример использования Promise.allSettled():
// const p1 = new Promise((resolve, reject) => {
//   setTimeout(resolve, 100, "John");
// });
// const p2 = Promise.reject("Error");
// const p3 = Promise.resolve(3);

// Promise.allSettled([p1, p2, p3]).then((values) => {
//     console.log(values);
// });
// =========================================================

// ?Работа метода Promise.allSettled()
// ● Promise, который будет выполнен после завершения каждого
// промиса, вне зависимости от того выполнился он успешно
// или был отклонен.
// ● В возвращаемый обработчик промиса передается массив,
// который содержит результат каждого промиса в исходном
// наборе промисов.
// ● Объект каждого результата содержит свойство status.
//     ○ Если status имеет значение fulfilled (выполнено), то объект будет содержать свойство value.
//     ○ Если status имеет значение rejected (отклонено), то объект будет содержать свойство reason.
// ● Свойство value (или reason) будет содержать значение с
// которым был выполнен (или отклонен) промис.
// =========================================================

// !Promise.any() — это метод,
// который принимает итерируемый объект содержащий объекты
// промисов Promise. Является противоположностью для
// Promise.all().

// *Пример использования Promise.any():
// const p1 = new Promise((resolve, reject) => {
//   setTimeout(resolve, 100, "John");
